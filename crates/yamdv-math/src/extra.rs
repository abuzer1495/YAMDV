/// Extra delimiter tokens for `\left`, `\right`, `\middle`, `\big…`.
pub fn delimiter(tok: &str) -> Option<char> {
    Some(match tok {
        "\\lbrack" => '[',
        "\\rbrack" => ']',
        "\\lang" => '⟨',
        "\\rang" => '⟩',
        "\\lgroup" => '⟮',
        "\\rgroup" => '⟯',
        "\\lmoustache" => '⎰',
        "\\rmoustache" => '⎱',
        "\\lBrack" | "\\llbracket" => '⟦',
        "\\rBrack" | "\\rrbracket" => '⟧',
        "\\ulcorner" => '⌜',
        "\\urcorner" => '⌝',
        "\\llcorner" => '⌞',
        "\\lrcorner" => '⌟',
        "\\updownarrow" => '↕',
        "\\Updownarrow" => '⇕',
        "\\arrowvert" => '⏐',
        "\\Arrowvert" => '‖',
        "\\bracevert" => '⎪',
        _ => return None,
    })
}

/// `\not` before a relation: the precomposed negated form when Unicode has one.
pub fn negate(c: char) -> Option<char> {
    Some(match c {
        '=' => '≠',
        '<' => '≮',
        '>' => '≯',
        '≤' => '≰',
        '≥' => '≱',
        '∈' => '∉',
        '∋' => '∌',
        '≡' => '≢',
        '∼' => '≁',
        '≃' => '≄',
        '≅' => '≇',
        '≈' => '≉',
        '⊂' => '⊄',
        '⊃' => '⊅',
        '⊆' => '⊈',
        '⊇' => '⊉',
        '∣' | '|' => '∤',
        '∥' => '∦',
        '≺' => '⊀',
        '≻' => '⊁',
        '⊢' => '⊬',
        '⊨' => '⊭',
        '→' => '↛',
        '←' => '↚',
        '↔' => '↮',
        '⇒' => '⇏',
        '⇐' => '⇍',
        '⇔' => '⇎',
        '∃' => '∄',
        _ => return None,
    })
}
