//! The FUT-17 core vocabulary: Greek letters, about 150 symbols/relations/arrows, big operators,
//! function names, delimiters, accents and named colors.

/// TeX atom class (spacing, §2.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Class {
    /// Ordinary.
    Ord,
    /// Large operator.
    Op,
    /// Binary operator.
    Bin,
    /// Relation.
    Rel,
    /// Opening delimiter.
    Open,
    /// Closing delimiter.
    Close,
    /// Punctuation.
    Punct,
    /// Inner (fractions with delimiters, `\left…\right`).
    Inner,
}

use Class::{Bin, Close, Open, Ord, Punct, Rel};

