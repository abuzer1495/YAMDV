/// Class of a plain character in math mode.
pub fn char_class(c: char) -> Class {
    match c {
        '+' | '-' | '*' | '−' | '±' | '×' | '÷' | '⋅' => Bin,
        '=' | '<' | '>' | ':' | '≤' | '≥' | '≠' | '→' | '←' => Rel,
        '(' | '[' | '⟨' => Open,
        ')' | ']' | '!' | '?' | '⟩' => Close,
        ',' | ';' => Punct,
        _ => Ord,
    }
}

/// Delimiter for `\left`/`\right`/`\big…` from a token (`None` = `.`, the null delimiter).
pub fn delimiter(tok: &str) -> Option<Option<char>> {
    Some(Some(match tok {
        "." => return Some(None),
        "(" => '(',
        ")" => ')',
        "[" => '[',
        "]" => ']',
        "|" | "\\vert" | "\\lvert" | "\\rvert" | "\\mid" => '|',
        "\\|" | "\\Vert" | "\\lVert" | "\\rVert" => '‖',
        "\\{" | "\\lbrace" => '{',
        "\\}" | "\\rbrace" => '}',
        "\\langle" | "<" => '⟨',
        "\\rangle" | ">" => '⟩',
        "\\lfloor" => '⌊',
        "\\rfloor" => '⌋',
        "\\lceil" => '⌈',
        "\\rceil" => '⌉',
        "/" => '/',
        "\\backslash" => '\\',
        "\\uparrow" => '↑',
        "\\downarrow" => '↓',
        "\\Uparrow" => '⇑',
        "\\Downarrow" => '⇓',
        _ => return None,
    }))
}

/// Named colors for `\color{…}` (`0xRRGGBB`).
pub fn color(name: &str) -> Option<u32> {
    let n = name.trim();
    if let Some(hex) = n.strip_prefix('#') {
        let ok = hex.chars().all(|c| c.is_ascii_hexdigit());
        return match (ok, hex.len()) {
            (true, 6) => u32::from_str_radix(hex, 16).ok(),
            (true, 3) => {
                let v = u32::from_str_radix(hex, 16).ok()?;
                let (r, g, b) = ((v >> 8) & 0xF, (v >> 4) & 0xF, v & 0xF);
                Some(((r * 17) << 16) | ((g * 17) << 8) | (b * 17))
            }
            _ => None,
        };
    }
    Some(match n.to_ascii_lowercase().as_str() {
        "black" => 0x000000,
        "white" => 0xffffff,
        "red" => 0xdf0030,
        "green" => 0x008b00,
        "blue" => 0x0000ff,
        "cyan" => 0x00b7eb,
        "magenta" => 0xec008c,
        "yellow" => 0xfff200,
        "orange" => 0xff8c00,
        "purple" => 0x8000ff,
        "violet" => 0x8f00ff,
        "brown" => 0x964b00,
        "gray" | "grey" => 0x808080,
        "lightgray" | "lightgrey" => 0xc0c0c0,
        "darkgray" | "darkgrey" => 0x404040,
        "teal" => 0x008080,
        "olive" => 0x808000,
        "pink" => 0xff69b4,
        "lime" => 0x32cd32,
        "navy" => 0x000080,
        "maroon" => 0x800000,
        _ => return None,
    })
}
